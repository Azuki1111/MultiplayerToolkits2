-- ============================================================================
-- 条目20扩展2：阶段计时器回合节点表（数据驱动平滑曲线）
-- 脚本在相邻两个回合节点之间对回合时间做线性插值：首节点前保持首节点时间、
--   末节点后保持末节点时间。默认节点即用户给定示例：
--   (30,30)/(50,80)/(70,180) → 1~30T 保持 30 秒、30~50T 线性升至 80 秒、
--   50~70T 线性升至 180 秒、之后保持 180 秒。
-- 自定义曲线：直接增删改下面的 VALUES 行（Turn=回合数，Time=该回合的秒数），
--   脚本自动按 Turn 升序插值，无需改代码。
-- 注册于 InGameActions（本表仅游戏内脚本消费，前端不读）。
-- ============================================================================
CREATE TABLE IF NOT EXISTS MPT_TimerTiers (
	Turn INTEGER NOT NULL,
	Time INTEGER NOT NULL,
	PRIMARY KEY(Turn)
);

INSERT OR REPLACE INTO MPT_TimerTiers (Turn, Time)
VALUES 
	(0, 20),
	(8, 30),
	(15, 40),
	(20, 50),
	(30, 75),
	(35, 100),
	(50, 140),
	(70, 180),
	(90, 220);
